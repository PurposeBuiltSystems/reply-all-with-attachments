/* Structural regressions for Outlook signature HTML; no live mailbox needed. */
"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const { JSDOM } = require("jsdom");
const document = new JSDOM("<!doctype html><html><body></body></html>").window.document;
const context = { document, Office: { onReady() {}, actions: { associate() {} } }, Date, Math };
context.self = context;
context.window = context;
for (const file of ["signature-layout.js", "commands/commands.js", "taskpane/taskpane.js"]) {
  vm.runInNewContext(fs.readFileSync(path.join(__dirname, "../src", file), "utf8"), context);
}
const { SignatureLayout: layout } = context;
const pasted = '<style><!-- .MsoNormal { text-align: center; margin:0 } --></style><p class="MsoNormal">Signature text</p><p><img src="data:image/png;base64,YWJj"></p>';
const cleaned = context.cleanPastedHtml(pasted);
let box = document.createElement("div"); box.innerHTML = cleaned;
assert.equal(box.querySelector("p").getAttribute("align"), "center", "stylesheet-only centering survives paste cleanup");
assert.equal(box.querySelector("p").style.textAlign, "center");
assert.equal(box.querySelector("style"), null);
const explicit = context.cleanPastedHtml('<style>.x{text-align:center}</style><p class="x" style="text-align:right">Text</p>');
box.innerHTML = explicit;
assert.equal(box.querySelector("p").getAttribute("align"), "right", "inline alignment takes precedence");
box.innerHTML = '<div><img style="display:block;margin-left:auto;margin-right:auto" src="data:image/png;base64,YWJj"></div>';
layout.stabilize(box);
layout.imagesBelowText(box);
assert.equal(box.firstChild.getAttribute("align"), "left", "logo footer is explicitly left aligned");
assert.equal(box.querySelector("img").style.marginLeft, "0px");
box.innerHTML = '<table><tr><td><img src="data:image/png;base64,YWJj"></td><td>Name</td></tr></table>';
const img = box.querySelector("img");
Object.defineProperties(img, { naturalWidth: { value: 960 }, naturalHeight: { value: 480 } });
layout.stabilize(box, 320);
assert.equal(img.getAttribute("width"), "320");
assert.equal(img.getAttribute("height"), "160");
layout.imagesBelowText(box);
assert.equal(img.style.display, "block", "logo occupies its own line beneath text");
assert.equal(box.lastElementChild.contains(img), true);
assert.equal(box.querySelector("table").textContent, "Name");
assert.equal(box.querySelectorAll("td").length, 2);
box.innerHTML = '<p align="center"><img width="150" height="75" src="data:image/png;base64,YWJj"></p>';
layout.stabilize(box);
assert.equal(box.querySelector("img").getAttribute("width"), "150", "preserve chosen image size");
const sig = layout.prepare(box.innerHTML);
const original = '<html><head><style>body{text-align:right}</style></head><body><p>Quoted</p></body></html>';
const result = context.prependSignature(original, sig);
assert.ok(result.startsWith("<html>"), "signature is not prepended outside the document");
const parsed = new JSDOM(result).window.document;
assert.equal(parsed.body.firstElementChild.textContent, "", "an empty line to type on comes before the signature");
const sigBlock = parsed.body.firstElementChild.nextElementSibling;
assert.equal(sigBlock.getAttribute("align"), "left", "isolate signature from quoted-thread alignment");
assert.equal(sigBlock.querySelector("p").getAttribute("align"), "left");
assert.equal(parsed.querySelector("head style").textContent, "body{text-align:right}");
assert.equal(parsed.body.lastElementChild.textContent, "Quoted");
const nested = layout.prepare('<div style="text-align:center"><p>Centered text</p><p><img src="data:image/png;base64,YWJj"></p></div><p>Left text</p>');
const nestedDoc = new JSDOM(nested).window.document;
assert.equal(nestedDoc.querySelectorAll("p")[0].style.textAlign, "center", "inherited center becomes explicit before joining quoted HTML");
assert.equal(nestedDoc.querySelectorAll("p")[1].style.textAlign, "left", "ordinary signature text stays left aligned");
const oldSignature = '<p><a href="https://example.com"><img align="right" style="float:right;position:absolute;left:20px" width="150" src="data:image/png;base64,YWJj"></a>Name</p><p>Title</p>';
box.innerHTML = layout.prepare(oldSignature);
const footer = box.querySelector("[data-raa-image-footer]");
assert.equal(footer.closest("tr").previousElementSibling.textContent, "NameTitle");
assert.equal(footer.querySelector("a").getAttribute("href"), "https://example.com");
assert.equal(footer.querySelector("img").style.cssFloat, "none");
assert.equal(footer.querySelector("img").style.position, "static");
assert.equal(footer.querySelector("img").style.left, "");
box.innerHTML = layout.prepare(box.innerHTML);
assert.equal(box.querySelectorAll("[data-raa-image-footer]").length, 1, "repeated normalization keeps one footer");
assert.equal(box.querySelectorAll("img").length, 1);
// A floated text table and positioned logo link used to escape the footer's
// CSS clear rule. Check the actual row boundary used by Outlook's renderer.
box.innerHTML = layout.prepare('<table align="left" style="float:left;mso-table-lspace:12pt"><tr><td>Name<br>Title</td></tr></table><a href="https://example.com" style="position:absolute;left:200px;mso-position-horizontal:right"><img width="150" src="data:image/png;base64,YWJj"></a>');
const frame = box.querySelector("table[data-raa-layout]");
assert.equal(frame.rows.length, 2);
assert.equal(frame.rows[0].cells.length, 1);
assert.equal(frame.rows[1].cells.length, 1);
assert.equal(frame.rows[0].querySelector("img"), null);
assert.equal(frame.rows[1].querySelectorAll("img").length, 1);
assert.equal(frame.rows[0].textContent, "NameTitle");
const textTable = frame.rows[0].querySelector("table");
assert.equal(textTable.hasAttribute("align"), false);
assert.equal(textTable.style.cssFloat, "none");
assert.equal(/mso-table-lspace/.test(textTable.getAttribute("style")), false);
const logoLink = frame.rows[1].querySelector("a");
assert.equal(logoLink.style.position, "static");
assert.equal(logoLink.style.left, "");
assert.equal(/mso-position/.test(logoLink.getAttribute("style")), false);
assert.equal(logoLink.href, "https://example.com/");
assert.equal(logoLink.querySelector("img").getAttribute("width"), "150");
box.innerHTML = layout.prepare(box.innerHTML);
assert.equal(box.querySelectorAll("table[data-raa-layout]").length, 1);
assert.equal(box.textContent, "NameTitle");
assert.equal(box.querySelectorAll("img").length, 1);
context.sigEl = document.createElement("div");
context.sigEl.innerHTML = '<p>Name</p><p>Title</p>';
context.appendImageAtEnd("data:image/png;base64,YWJj");
assert.equal(context.sigEl.lastElementChild.previousElementSibling.textContent, "Title");
assert.equal(context.sigEl.lastElementChild.querySelector("img").style.display, "block");
context.appendImageAtEnd("data:image/png;base64,ZGVm");
assert.equal(context.sigEl.querySelectorAll("[data-raa-image-footer]").length, 1);
assert.equal(context.sigEl.lastElementChild.querySelectorAll("p").length, 2);
const first = context.extractInlineImages(sig), second = context.extractInlineImages(sig);
assert.notEqual(first.images[0].cid, second.images[0].cid, "quoted older signatures cannot collide with a new logo CID");
assert.equal(context.referencesImage('src="cid:' + encodeURIComponent(first.images[0].cid) + '"', first.images[0].cid), true);
assert.equal(first.images[0].contentBytes, "YWJj");
console.log("All signature layout regression tests passed.");
